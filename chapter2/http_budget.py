class HttpCallBudget:
    def __init__(self, total_seconds: float):
        self._deadline = time.monotonic() + total_seconds

    def seconds_remaining(self) -> float:
        return self._deadline - time.monotonic()

    def next_call_timeout(self, calls_left: int, floor_s: float = 4.0) -> float:
        """????????????????????????? 0?"""
        left = self.seconds_remaining()
        if left < floor_s + 0.5:
            return 0.0
        share = (left - 0.5) / max(1, calls_left)
        return max(floor_s, share)
